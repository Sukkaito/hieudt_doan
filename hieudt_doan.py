def generate_ai_comment(scores: dict) -> dict:
    """
    Gọi Ollama local (qwen2.5:3b) để sinh nhận xét chuyên sâu
    dựa trên điểm số của 8 góc khớp.
    """

    # Xây dựng phần điểm chi tiết
    score_lines = "\n".join(
        f"- {ANGLE_LABELS_VI[key]:<20}: {scores.get(key, 0):.1f}/100"
        for key in ANGLE_KEYS
    )

    # Liệt kê các khớp yếu (< 80 điểm) để AI tập trung phân tích
    weak_joints = [
        f"{ANGLE_LABELS_VI[k]} ({scores.get(k, 0):.1f}/100)"
        for k in ANGLE_KEYS if scores.get(k, 0) < 80
    ]
    weak_text = ", ".join(weak_joints) if weak_joints else "Không có khớp yếu"

    prompt = (
        "Bạn là giảng viên thể dục quốc phòng tại trường đại học Việt Nam. "
        "Nhiệm vụ của bạn là đánh giá tư thế thực hiện động tác quốc phòng của sinh viên "
        "dựa trên phân tích góc độ 8 khớp cơ thể được đo bằng AI.\n\n"

        "=== KẾT QUẢ PHÂN TÍCH TƯ THẾ (thang 100) ===\n"
        f"{score_lines}\n"
        f"- {'Tổng điểm':<20}: {scores.get('overall', 0):.1f}/100\n\n"

        f"=== CÁC KHỚP CẦN CẢI THIỆN (< 80 điểm) ===\n"
        f"{weak_text}\n\n"

        "=== HƯỚNG DẪN ĐÁNH GIÁ ===\n"
        "Với mỗi khớp có điểm DƯỚI 80, hãy phân tích:\n"
        "1. Lỗi tư thế thường gặp trong các động tác quốc phòng tại khớp đó\n"
        "   (ví dụ: vai không thẳng khi đứng nghiêm, hông lệch khi quay đều,\n"
        "    gối không đúng góc khi bước đều...)\n"
        "2. Cách khắc phục theo đúng điều lệnh quân sự\n"
        "3. Bài tập cụ thể để cải thiện khớp đó\n\n"

        "Với các khớp có điểm TỪ 80 TRỞ LÊN, hãy ghi nhận điểm mạnh.\n\n"

        "Chỉ trả về JSON thuần (không markdown, không giải thích thêm):\n"
        '{'
        '"comment": "Nhận xét tổng quan về phong cách thực hiện động tác",'
        '"strengths": ["Điểm mạnh 1", "Điểm mạnh 2"],'
        '"suggestions": ['
        '  {"joint": "Tên khớp", "score": 0, "issue": "Mô tả lỗi", "fix": "Cách khắc phục", "exercise": "Bài tập"}'
        '],'
        '"priority": "Khớp quan trọng nhất cần tập trung cải thiện trước"'
        '}'
    )

    try:
        print(f"🚀 Calling Ollama ({OLLAMA_MODEL})...")
        response = requests.post(
            OLLAMA_URL,
            json={
                "model":  OLLAMA_MODEL,
                "prompt": prompt,
                "stream": False,
                "format": "json",
                "options": {
                    "temperature": 0.3,
                    "num_predict": 800   # tăng lên để đủ chỗ cho 8 khớp
                }
            },
            timeout=180
        )
        raw = response.json().get("response", "")
        print(f"📩 Ollama raw:\n{raw[:400]}")

        json_match = re.search(r'\{[\s\S]*\}', raw)
        if not json_match:
            raise ValueError("Không tìm thấy JSON trong response")

        parsed = json.loads(json_match.group())
        print("✅ Ollama parsed OK")
        return parsed

    except Exception as e:
        print(f"❌ Ollama FAILED [{type(e).__name__}]: {e}")

        # Fallback: tự tạo nhận xét đơn giản dựa trên điểm
        overall = scores.get("overall", 0)
        auto_suggestions = [
            {
                "joint":    ANGLE_LABELS_VI[k],
                "score":    scores.get(k, 0),
                "issue":    "Góc khớp chưa đạt chuẩn so với mẫu",
                "fix":      "Quan sát lại video mẫu và điều chỉnh tư thế",
                "exercise": "Tập luyện lặp lại động tác chậm trước gương"
            }
            for k in ANGLE_KEYS if scores.get(k, 0) < 80
        ]
        auto_strengths = [
            f"{ANGLE_LABELS_VI[k]} đạt {scores.get(k, 0):.0f}/100"
            for k in ANGLE_KEYS if scores.get(k, 0) >= 80
        ]

        return {
            "comment":     f"Tổng điểm đạt {overall:.1f}/100. {'Thực hiện tốt, tiếp tục duy trì.' if overall >= 80 else 'Cần tập luyện thêm để cải thiện tư thế.'}",
            "suggestions": auto_suggestions,
            "strengths":   auto_strengths if auto_strengths else ["Đã hoàn thành bài kiểm tra."],
            "priority":    min(
                (k for k in ANGLE_KEYS if scores.get(k, 0) < 80),
                key=lambda k: scores.get(k, 100),
                default=""
            )
        }

