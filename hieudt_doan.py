def extract_angle_sequence(data: dict, angle_key: str) -> list:
    return [f["angles"][angle_key] for f in data.get("frames", [])]

def calculate_dtw_score(std_seq: list, stu_seq: list) -> float:
    """
    So sánh 2 chuỗi góc bằng Dynamic Time Warping.
    - Lệch 0°  → 100 điểm
    - Lệch 45° → 0 điểm
    """
    if not std_seq or not stu_seq:
        return 0.0
    distance, path = fastdtw(std_seq, stu_seq, dist=lambda x, y: abs(x - y))
    avg_distance   = distance / len(path) if path else 180.0
    score          = 100.0 * (1.0 - (avg_distance / 45.0))
    return max(0.0, min(100.0, round(score, 2)))

