@app.post("/api/ai/compare-pose")
async def compare_pose(request: ComparePoseRequest):
    """
    So sánh DTW cho cả 8 góc khớp.
    Điểm overall = trung bình cộng 8 góc.
    """
    try:
        std, stu = request.standardData, request.studentData

        scores = {
            key: calculate_dtw_score(
                extract_angle_sequence(std, key),
                extract_angle_sequence(stu, key)
            )
            for key in ANGLE_KEYS
        }

        scores["overall"] = round(sum(scores.values()) / len(ANGLE_KEYS), 2)

        return {
            "status":  "success",
            "message": "Comparison completed",
            "scores":  scores
        }
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))

