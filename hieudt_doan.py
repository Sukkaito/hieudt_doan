@app.post("/api/ai/evaluate")
async def evaluate(request: EvaluateRequest):
    """
    Tạo biểu đồ 8 góc + AI nhận xét chi tiết song song.
    """
    try:
        loop = asyncio.get_event_loop()

        charts_task  = loop.run_in_executor(
            executor, build_chart_data, request.standardData, request.studentData
        )
        comment_task = loop.run_in_executor(
            executor, generate_ai_comment, request.scores
        )

        charts, ai_result = await asyncio.gather(charts_task, comment_task)

        return {
            "status":  "success",
            "message": "Evaluation completed successfully",
            "evaluation": {
                "rating":      get_rating(request.scores.get("overall", 0)),
                "comment":     ai_result.get("comment",     "Chưa có nhận xét."),
                "suggestions": ai_result.get("suggestions", []) if isinstance(ai_result.get("suggestions"), list) else [],
                "strengths":   ai_result.get("strengths",   []) if isinstance(ai_result.get("strengths"),   list) else [],
                "priority":    ai_result.get("priority",    ""),
            },
            "scores": request.scores,
            "charts": charts
        }

    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))

