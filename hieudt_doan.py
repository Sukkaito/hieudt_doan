def build_chart_data(standard_data: dict, student_data: dict) -> dict:
    """Tạo dữ liệu biểu đồ cho cả 8 góc."""
    charts     = {}
    std_frames = standard_data.get("frames", [])
    stu_frames = student_data.get("frames",  [])

    for key in ANGLE_KEYS:
        charts[key] = {
            "label": ANGLE_LABELS_VI[key],
            "standard": {
                "labels": [f["timestamp"]   for f in std_frames],
                "values": [f["angles"][key] for f in std_frames]
            },
            "student": {
                "labels": [f["timestamp"]   for f in stu_frames],
                "values": [f["angles"][key] for f in stu_frames]
            }
        }

    return charts

def get_rating(score: float) -> str:
    if   score >= 90: return "Xuất sắc"
    elif score >= 75: return "Khá"
    elif score >= 60: return "Trung bình"
    else:             return "Cần cải thiện"

